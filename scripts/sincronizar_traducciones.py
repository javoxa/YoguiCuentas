#!/usr/bin/env python3
"""Regenerate or check the Metal catalogue from the shared Spanish/English source."""
from pathlib import Path
import argparse
import json
import runpy

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true',help='Check without modifying files')
args=parser.parse_args()
root=Path(__file__).resolve().parents[1]
en=runpy.run_path(str(root/'yoguicuentas/ui/translations.py'))['EN']
target=root/'metal/yoguicuentas_metal/Sources/YoguiCuentasMetal/TranslationCatalogue.swift'
quote=lambda value:json.dumps(value,ensure_ascii=False)
content=('// Generated by scripts/sincronizar_traducciones.py; edit translations.py.\n'
         'import Foundation\n\nextension L10n {\n    static let english: [String: String] = [\n'
         +''.join('        '+quote(key)+': '+quote(value)+',\n' for key,value in sorted(en.items()))
         +'    ]\n}\n')
if args.check:
    if not target.exists() or target.read_text()!=content:
        raise SystemExit('Catalogue out of date: run python3 scripts/sincronizar_traducciones.py')
else:
    target.write_text(content)
print(f'{len(en)} translations synchronised')
